def main():
    if not os.path.exists(INPUT_FOLDER):
        print(f"❌ Input folder not found: {INPUT_FOLDER}")
        print(f"   Please set INPUT_FOLDER to your images folder path.")
        return

    # Get all image files
    exts = {'.jpg', '.jpeg', '.png', '.webp'}
    all_files = [
        f for f in os.listdir(INPUT_FOLDER)
        if os.path.splitext(f.lower())[1] in exts
    ]
    print(f"✓ Found {len(all_files)} images in {INPUT_FOLDER}/")

    os.makedirs(OUTPUT_FOLDER, exist_ok=True)

    # ── Parse filenames to extract base name + number ────────
    # Current format: "College Name_1.jpg" or "College Name_2.jpg"
    # Also handle: "College Name.jpg" (no number)
    file_groups = {}  # base_name → list of (number, filename)

    for fname in sorted(all_files):
        name, ext = os.path.splitext(fname)

        # Try to extract trailing _1 or _2
        m = re.match(r'^(.+?)_(\d+)$', name)
        if m:
            base   = m.group(1).strip()
            number = int(m.group(2))
        else:
            base   = name.strip()
            number = 1

        if base not in file_groups:
            file_groups[base] = []
        file_groups[base].append((number, fname))

    print(f"✓ Found {len(file_groups)} unique colleges in filenames")

    # ── Match each group to DB name ──────────────────────────
    results      = []
    unmatched    = []
    used_db_names = {}  # db_name → count of images already assigned

    for base_name, file_list in sorted(file_groups.items()):
        # Sort files by their number
        file_list_sorted = sorted(file_list, key=lambda x: x[0])

        # Find matching DB name
        db_name, score = find_best_match(base_name, DB_COLLEGE_NAMES)

        if db_name is None:
            print(f"   ✗ NO MATCH ({score:.2f}): {base_name[:60]}")
            for num, fname in file_list_sorted:
                unmatched.append(fname)
                results.append({
                    "original_file":  fname,
                    "detected_base":  base_name,
                    "db_name":        "NO MATCH",
                    "match_score":    round(score, 3),
                    "new_filename":   "",
                    "status":         "unmatched",
                })
            continue

        # Assign sequential numbers (1, 2) regardless of original numbers
        # This handles the case where _2 was deleted and only _1 remains, etc.
        img_count = len(file_list_sorted)
        print(f"   ✓ ({score:.2f}) {db_name[:55]} [{img_count} img]")

        for i, (orig_num, fname) in enumerate(file_list_sorted, 1):
            # New filename = exact DB name + _1 or _2
            safe_db = re.sub(r'[<>:"/\\|?*\n\r\t]', '', db_name)
            safe_db = re.sub(r'\s+', ' ', safe_db).strip()[:120]
            new_fname = f"{safe_db}_{i}.jpg"

            src = os.path.join(INPUT_FOLDER,  fname)
            dst = os.path.join(OUTPUT_FOLDER, new_fname)

            shutil.copy2(src, dst)

            results.append({
                "original_file":  fname,
                "detected_base":  base_name,
                "db_name":        db_name,
                "match_score":    round(score, 3),
                "new_filename":   new_fname,
                "status":         "renamed",
            })

