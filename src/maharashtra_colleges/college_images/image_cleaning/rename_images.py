def normalize(text):
    """Normalize text for matching — lowercase, remove extra spaces/punctuation."""
    text = text.lower().strip()
    text = re.sub(r'[^\w\s]', ' ', text)   # remove punctuation
    text = re.sub(r'\s+', ' ', text).strip()
    return text

def similarity(a, b):
    """Fuzzy similarity score between two strings."""
    return SequenceMatcher(None, normalize(a), normalize(b)).ratio()

def find_best_match(filename_base, db_names, threshold=0.75):
    """
    Find the best matching DB college name for a given filename.
    Returns (db_name, score) or (None, 0) if no good match.
    """
    best_name  = None
    best_score = 0

    fn_norm = normalize(filename_base)

    for db_name in db_names:
        db_norm = normalize(db_name)

        # Exact match after normalization
        if fn_norm == db_norm:
            return db_name, 1.0

        # Check if filename starts with or contains DB name
        score = similarity(filename_base, db_name)

        # Boost score if one contains the other
        if fn_norm in db_norm or db_norm in fn_norm:
            score = max(score, 0.85)

        if score > best_score:
            best_score = score
            best_name  = db_name

    if best_score >= threshold:
        return best_name, best_score
    return None, best_score

